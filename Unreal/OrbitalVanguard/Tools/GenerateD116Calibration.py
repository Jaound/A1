"""Generate immutable UE candidate data from D116. Run from any working directory."""
import hashlib
import json
from pathlib import Path
import sys

project = Path(__file__).resolve().parents[1]
source = project.parents[1] / "reference/IntegratedCombat/profile.json"
output = project / "Source/OrbitalVanguard/OVCalibrationData.inl"
raw = source.read_bytes()
profile = json.loads(raw)
weapons = profile["weapons"]
integration = profile["integration"]

def numeric(value):
    return f"{float(value):.9f}f"

def values(*items):
    return ", ".join(numeric(value) for value in items)

lines = [
    "// Generated by Tools/GenerateD116Calibration.py. Distances and speeds already in cm and cm/s.",
    f'constexpr TCHAR SourceHash[] = TEXT("{hashlib.sha256(raw).hexdigest()}");',
    "constexpr float TierDamage[] = {" + values(*(profile["tier_damage"][str(t)] for t in range(1, 5))) + "};",
    "constexpr float ShieldCombat = " + numeric(integration["combat_regen"]) + ";",
    "constexpr float ShieldNonCombat = " + numeric(integration["noncombat_regen"]) + ";",
    "constexpr float ShieldTransition = " + numeric(integration["noncombat_after"]) + ";",
    "constexpr float ShieldDelay = " + numeric(integration["shield_delay"]) + ";",
    "constexpr float CrewInjury = " + numeric(integration["crew_injury_fraction"]) + ";",
    "constexpr float SalvoInterval = " + numeric(integration["salvo_interval"]) + ";",
    "constexpr FWeapon Weapons[] = {",
]
kinds = ("Beam", "Beam", "Cannon", "Cannon", "Missile", "GuidedMissile", "Cannon")
for (key, w), kind in zip(((key, weapons[key]) for key in ("beam", "heavy_beam", "cannon", "heavy_cannon", "missile", "guided", "spinal")), kinds):
    lines.append(f'    {{TEXT("{key}"), EOVAttackKind::{kind}, {w.get("minimum_tier",1)}, {w["salvo"]}, '
                 + values(w["damage"], w["period"], w["range"]*100, w["speed"]*100, w["turn"], w["hp"],
                          w["spread_deg"], w.get("guide_turn",0), w.get("lifetime",0)) + "},")
lines += ["};", "constexpr FRadar Radars[] = {"]
for tier, radar in sorted(profile["radar"].items()):
    lines.append(f'    {{{tier}, ' + values(radar["range"]*100, radar["bonus"]) + "},")
lines += ["};", "constexpr FHull Hulls[] = {"]
weapon_indices = {key: index for index, key in enumerate(("beam", "heavy_beam", "cannon", "heavy_cannon", "missile", "guided", "spinal"))}
for key, h in profile["ships"].items():
    mounts = ", ".join(f'{{{weapon_indices[w["kind"]]}, {w["tier"]}, {str(w["mount"] == "top").lower()}}}' for w in h["weapons"])
    lines.append(f'    {{TEXT("{key}"), {h["size"]}, {h["decks"]}, {h["pd"]}, {h["radar_tier"]}, '
                 + values(h["hp"], h["shield"], h["armor_cell"], h["front_armor"], h["speed"]*100, h["hull_turn"])
                 + f', {len(h["weapons"])}, {{{mounts}}}}},')
lines += ["};", ""]
generated = "\n".join(lines)
if "--check" in sys.argv:
    if output.read_text(encoding="utf-8") != generated:
        raise SystemExit("D116 data differs from source mapping")
else:
    output.write_text(generated, encoding="utf-8")
