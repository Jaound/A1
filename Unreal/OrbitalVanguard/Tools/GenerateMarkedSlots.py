"""사용자 도면의 투영 후보를 검증 가능한 C++ 슬롯 후보로 변환한다.

서로 다른 투영면은 서로 다른 슬롯이다. 후보는 UE 메시 검증 전까지 장착하지 않는다.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[3]
source = root / 'docs/validation/PlayUIR2/JX_무장표시_표면투영후보.json'
destination = Path(__file__).resolve().parents[1] / 'Source/OrbitalVanguard/OVMarkedSlotsData.inl'
data = json.loads(source.read_text(encoding='utf-8'))
lines = ['// Generated by Tools/GenerateMarkedSlots.py; positions are unverified candidates.']
seen = set()
kind = {'yellow': 'Interception', 'blue': 'General', 'red': 'Dedicated'}
for ship in data['ships']:
    for slot in ship['candidates']:
        key = (ship['id'], slot['view'], slot['color'], slot['region'])
        if key in seen or not slot['hit']:
            raise ValueError(f'duplicate or unprojected slot: {key}')
        seen.add(key)
        position = ', '.join(f'{x:.9f}' for x in slot['local_cm'])
        normal = ', '.join(f'{x:.9f}' for x in slot['normal'])
        ident = f"{slot['view']}_{slot['color']}_{slot['region']}"
        lines.append(f'    {{TEXT("{ship["id"]}"), TEXT("{ident}"), EOVMarkedSlotKind::{kind[slot["color"]]}, FVector({position}), FVector({normal})}},')
destination.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'{len(seen)} independent marked slot candidates')
