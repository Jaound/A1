"""검증용 선체 상자 후보를 런타임 실험 데이터로 생성한다."""
import json
from pathlib import Path

project = Path(__file__).resolve().parents[1]
source = project.parents[1] / 'docs/validation/PlayUIR2/KQ_선체충돌_후보.json'
destination = project / 'Source/OrbitalVanguard/OVHullCollisionCandidateData.inl'
data = json.loads(source.read_text(encoding='utf8'))
lines = ['// Generated by Tools/GenerateHullCollisionData.py; experimental hull approximation.']
for hull in data['ships']:
    if not 1 <= len(hull['boxes']) <= 32:
        raise ValueError(hull['hull'])
    for box in hull['boxes']:
        center = ', '.join(f'{x:.9f}' for x in box['local_center_cm'])
        extent = ', '.join(f'{x:.9f}' for x in box['half_extent_cm'])
        lines.append(f'    {{TEXT("{hull["hull"]}"), FVector({center}), FVector({extent})}},')
destination.write_text('\n'.join(lines) + '\n', encoding='utf8')
print('hulls:', len(data['ships']), 'boxes:', len(lines)-1)
